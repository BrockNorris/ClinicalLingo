"""Runs the example inputs used in the write-up and saves outputs + log lines.

    python cl.py ...  is the CLI; this script drives the Pipeline directly so the
    three runs land in one Markdown file (docs/example_runs.md) with their log lines.

Usage (Ollama must be running):
    python examples/run_examples.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from clinicallingo.output import render, render_quiz  # noqa: E402
from clinicallingo.pipeline import Pipeline  # noqa: E402
from clinicallingo.runlog import setup_logging  # noqa: E402

EXAMPLES = [
    {
        "title": "Example 1 - word mode, term in the dictionary",
        "text": "hypoechoic", "mode": "word", "web": False,
        "quiz": ["It looks darker than the tissue around it because fewer echoes come back", "something to do with blood flow"],
    },
    {
        "title": "Example 2 - sentence mode, plain-language rewrite",
        "text": "Sonographic findings of acute cholecystitis include cholelithiasis, gallbladder wall thickening greater than 3 mm, pericholecystic fluid, and a positive sonographic Murphy sign.",
        "mode": "sentence", "web": False, "quiz": [],
    },
    {
        "title": "Example 3 - word mode, term NOT in the dictionary (web tool call)",
        "text": "pneumobilia", "mode": "word", "web": True, "quiz": [],
    },
]


def main() -> int:
    setup_logging(False)
    out = ["# Example runs\n", "Generated by `examples/run_examples.py`. Each block shows the input, the rendered output, and the JSON log line written to `logs/runs.jsonl`.\n"]
    for ex in EXAMPLES:
        pipe = Pipeline(allow_web=ex["web"])
        result, retrieval, entry = pipe.explain(ex["text"], ex["mode"], force_web=ex["web"])
        out.append(f"\n## {ex['title']}\n")
        out.append(f"**Input** (`--mode {ex['mode']}`{' --web' if ex['web'] else ' --no-web'}):\n\n> {ex['text']}\n")
        out.append("**Output:**\n\n```text\n" + (render(result, retrieval) if result else f"Input rejected: {entry.error}") + "\n```\n")
        slim = entry.model_dump(exclude_none=True)
        slim["output"] = {k: v for k, v in slim["output"].items() if k != "rendered"}
        out.append("**Log line:**\n\n```json\n" + json.dumps(slim, indent=1)[:3000] + "\n```\n")
        if ex["quiz"] and result and retrieval and retrieval.chunks:
            answers = iter(ex["quiz"])
            rounds, qlog = pipe.quiz(result, retrieval, lambda q: next(answers, ""), n=len(ex["quiz"]))
            out.append("**Feedback loop (`--quiz`, answers pre-supplied):**\n\n```text\n" + render_quiz(rounds) + "\n```\n")
            out.append("**Quiz log line:**\n\n```json\n" + json.dumps(qlog.model_dump(exclude_none=True), indent=1)[:2500] + "\n```\n")
        print(f"done: {ex['title']} -> status={entry.status} total={entry.latency_ms.get('total')}ms")
    dest = ROOT / "docs" / "example_runs.md"
    dest.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {dest}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
